# Integer Data Type
print(3)

#decimal Data Type
print(2.5)

# how to find the type
print(type(3))
print(type(2.5))

# Boolean Data Type
print(True)
print(False)
print(type(True))
print(type(False))

# String
print("Hello World")
print(type("Helllo world"))

# Complex Data Type
print(5 + 7j)
print(type(5 + 7j))

# list Data type
print([1,2 , 3])
print(type([1 , 2, 3]))

# Tuple Data Type
print(( 2 ,3 , 5))
print(type((2 , 3 , 4)))


# Set Data Type
print({2 , 4, 5})
print(type({ 2 , 4 , 6, 7}))

# Dictionary Data type
print({"Key":12 , "Name":34})
print(type({"Key":12 , "Name":34}))